function getFilteredSeries() {
  const query = searchInput.value.trim().toLowerCase();

  return series.filter((item) => {
    const matchesFilter = activeFilter === "all" || item.type === activeFilter;
    const matchesSearch =
      item.title.toLowerCase().includes(query) ||
      item.genre.toLowerCase().includes(query);

    return matchesFilter && matchesSearch;
  });
}

function updateSeries() {
  renderSeries(getFilteredSeries());
}

function openDetailModal(seriesId) {
  selectedSeriesId = seriesId;
  const item = series.find((entry) => entry.id === seriesId);
  if (!item) return;

  detailCover.style.backgroundImage = `linear-gradient(180deg, rgba(15, 23, 42, 0.12), rgba(15, 23, 42, 0.42)), url('${item.image}')`;
  detailStatus.textContent = item.status;
  detailTitle.textContent = item.title;
  detailRating.textContent = `★ ${item.rating}`;
  detailDescription.textContent = item.description;
  detailAuthor.textContent = item.author;
  detailGenre.textContent = item.genre;
  detailChapters.textContent = `${item.chapters} capítulos`;

  chapterList.innerHTML = item.chaptersList
    .map(
      (chapter, index) => `
        <button class="chapter-item" data-chapter-index="${index}" data-series-id="${item.id}">
          <strong>Cap. ${chapter.number}</strong>
          <span>${chapter.title}</span>
        </button>
      `
    )
    .join("");

  detailModal.classList.remove("hidden");
  detailModal.setAttribute("aria-hidden", "false");
}

function closeDetailModal() {
  detailModal.classList.add("hidden");
  detailModal.setAttribute("aria-hidden", "true");
}

